#!/usr/bin/env bash
# Let Codex read this skill's files on hosts where its command sandbox cannot start.
#
# Codex reads skill references through shell commands, and every sandboxed command runs inside
# bubblewrap. Bubblewrap needs unprivileged user namespaces; hosts that restrict them (for example
# Ubuntu 24.04 with kernel.apparmor_restrict_unprivileged_userns=1) make every read fail with
# "bwrap: ... Operation not permitted", so the references are never loaded.
#
# This writes $CODEX_HOME/rules/formulate-strategy.rules, which allows only the skill's own
# scripts/read.sh. That script prints SKILL.md or references/<name>.md and refuses any other
# argument, so the rule cannot be used to read files outside the skill. (A rule for `cat <file>`
# would not be safe: Codex rules match command prefixes, so `cat <file> <other file>` would pass.)
# Every other command stays in the sandbox.
# Run it again after updating or moving the skill.
set -euo pipefail

codex_home="${CODEX_HOME:-$HOME/.codex}"
skill="$codex_home/skills/formulate-strategy"
if [ ! -f "$skill/SKILL.md" ]; then
  echo "Install the skill at $skill first (see README)." >&2
  exit 1
fi

real="$(cd "$skill" && pwd -P)"
out="$codex_home/rules/formulate-strategy.rules"
mkdir -p "$codex_home/rules"
{
  echo "# Generated by formulate-strategy/scripts/codex-allow-reads.sh."
  echo "# Allows only this skill's read-only scripts/read.sh."
  for base in "$skill" "$real"; do
    echo "prefix_rule(pattern=[\"$base/scripts/read.sh\"], decision=\"allow\")"
  done
} | awk '!seen[$0]++' > "$out"

echo "Wrote $out ($(grep -c prefix_rule "$out") rules)."
